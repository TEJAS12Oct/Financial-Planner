DROP TABLE IF EXISTS public.financial_planner_reports CASCADE;

DROP FUNCTION IF EXISTS
    public.set_financial_planner_reports_updated_at();

CREATE TABLE public.financial_planner_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT,

    full_name VARCHAR(255) NOT NULL,
    contact VARCHAR(20) NOT NULL,
    email VARCHAR(255) NOT NULL,
    dob VARCHAR(20) NOT NULL,
    city VARCHAR(100) NOT NULL,
    marital_status VARCHAR(30),

    dependents INTEGER NOT NULL DEFAULT 0,
    children_count INTEGER NOT NULL DEFAULT 0,

    monthly_income NUMERIC(18,2) NOT NULL DEFAULT 0,
    monthly_expenses NUMERIC(18,2) NOT NULL DEFAULT 0,
    monthly_savings NUMERIC(18,2) NOT NULL DEFAULT 0,
    spouse_income NUMERIC(18,2) NOT NULL DEFAULT 0,

    spouse_age BIGINT,

    risk_appetite VARCHAR(30),
    investment_experience VARCHAR(50),

    existing_life_term BOOLEAN NOT NULL DEFAULT FALSE,
    existing_health BOOLEAN NOT NULL DEFAULT FALSE,
    existing_critical BOOLEAN NOT NULL DEFAULT FALSE,
    existing_personal BOOLEAN NOT NULL DEFAULT FALSE,

    existing_life_term_cover NUMERIC(18,2) NOT NULL DEFAULT 0,
    existing_health_cover NUMERIC(18,2) NOT NULL DEFAULT 0,
    existing_critical_cover NUMERIC(18,2) NOT NULL DEFAULT 0,
    existing_personal_cover NUMERIC(18,2) NOT NULL DEFAULT 0,

    education1_inflation NUMERIC(5,2) NOT NULL DEFAULT 0,
    education1_lumpsum_return NUMERIC(5,2) NOT NULL DEFAULT 0,
    education1_s_ip_return NUMERIC(5,2) NOT NULL DEFAULT 0,
    education1_target_age BIGINT,

    marriage1_inflation NUMERIC(5,2) NOT NULL DEFAULT 0,
    marriage1_lumpsum_return NUMERIC(5,2) NOT NULL DEFAULT 0,
    marriage1_s_ip_return NUMERIC(5,2) NOT NULL DEFAULT 0,
    marriage1_target_age BIGINT,

    retirement_inflation NUMERIC(5,2) NOT NULL DEFAULT 0,
    retirement_pre_return NUMERIC(5,2) NOT NULL DEFAULT 0,
    retirement_post_return NUMERIC(5,2) NOT NULL DEFAULT 0,

    wealth_inflation NUMERIC(5,2) NOT NULL DEFAULT 0,
    wealth_lumpsum_return NUMERIC(5,2) NOT NULL DEFAULT 0,
    wealth_s_ip_return NUMERIC(5,2) NOT NULL DEFAULT 0,

    generic_goal_inflation NUMERIC(5,2) NOT NULL DEFAULT 0,
    generic_goal_lumpsum_return NUMERIC(5,2) NOT NULL DEFAULT 0,
    generic_goal_s_ip_return NUMERIC(5,2) NOT NULL DEFAULT 0,

    score_value BIGINT,
    score_label VARCHAR(100),

    status VARCHAR(50) NOT NULL DEFAULT 'report_requested',

    request_type VARCHAR(50),

    calculation_engine TEXT,
    calculation_status_code INTEGER NOT NULL DEFAULT 0,
    calculation_error_code VARCHAR(100),
    calculation_error_message TEXT,
    failed_module VARCHAR(100),

    calculation_engine_version VARCHAR(50),
    assumption_version VARCHAR(50),
    response_schema_version VARCHAR(50),

    pdf_status VARCHAR(50),
    storage_status VARCHAR(50),

    report_pdf_url TEXT,
    report_pdf_path TEXT,

    children_json JSONB,
    selected_goals_json JSONB,

    request_payload JSON,
    calculation_payload JSON,
    response_payload JSON,

    common_recommendations_title TEXT,
    common_recommendations_subtitle TEXT,
    common_recommendations JSONB,

    priority_roadmap JSONB,
    company_contact JSONB,
    customer JSONB,
    insurance_investment JSONB,
    email_status JSONB,
    database_status JSONB,

    generated_at TIMESTAMPTZ,

    goal_type_engine BOOLEAN NOT NULL DEFAULT FALSE,

    error_message TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_financial_planner_reports_children_count
        CHECK (children_count >= 0),

    CONSTRAINT chk_financial_planner_reports_dependents
        CHECK (dependents >= 0),

    CONSTRAINT chk_financial_planner_reports_spouse_age
        CHECK (spouse_age >= 0),

    CONSTRAINT chk_financial_planner_reports_financial_values
        CHECK (
            monthly_income >= 0
            AND monthly_expenses >= 0
            AND monthly_savings >= 0
            AND spouse_income >= 0
            AND existing_life_term_cover >= 0
            AND existing_health_cover >= 0
            AND existing_critical_cover >= 0
            AND existing_personal_cover >= 0
        )
);

CREATE INDEX idx_financial_planner_reports_user_id
ON public.financial_planner_reports(user_id);

CREATE INDEX idx_financial_planner_reports_email
ON public.financial_planner_reports(email);

CREATE INDEX idx_financial_planner_reports_city
ON public.financial_planner_reports(city);

CREATE INDEX idx_financial_planner_reports_status
ON public.financial_planner_reports(status);

CREATE INDEX idx_financial_planner_reports_request_type
ON public.financial_planner_reports(request_type);

CREATE INDEX idx_financial_planner_reports_pdf_status
ON public.financial_planner_reports(pdf_status);

CREATE INDEX idx_financial_planner_reports_storage_status
ON public.financial_planner_reports(storage_status);

CREATE INDEX idx_financial_planner_reports_created_at
ON public.financial_planner_reports(created_at DESC);

CREATE INDEX idx_financial_planner_reports_selected_goals_json
ON public.financial_planner_reports
USING GIN (selected_goals_json);

CREATE INDEX idx_financial_planner_reports_request_payload
ON public.financial_planner_reports
USING GIN ((request_payload::JSONB));

CREATE INDEX idx_financial_planner_reports_calculation_payload
ON public.financial_planner_reports
USING GIN ((calculation_payload::JSONB));

CREATE INDEX idx_financial_planner_reports_response_payload
ON public.financial_planner_reports
USING GIN ((response_payload::JSONB));

CREATE OR REPLACE FUNCTION
    public.set_financial_planner_reports_updated_at()
RETURNS TRIGGER AS
$$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$
LANGUAGE plpgsql;

CREATE TRIGGER trg_financial_planner_reports_updated_at
BEFORE UPDATE
ON public.financial_planner_reports
FOR EACH ROW
EXECUTE FUNCTION
    public.set_financial_planner_reports_updated_at();