DROP TABLE IF EXISTS public.financial_planner_selected_goals CASCADE;

DROP FUNCTION IF EXISTS
    public.set_financial_planner_selected_goals_updated_at();

CREATE TABLE public.financial_planner_selected_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    report_id BIGINT NOT NULL,

    goal_key VARCHAR(100),
    goal_label VARCHAR(255),
    goal_type VARCHAR(30),
    category_title VARCHAR(255),
    custom_name VARCHAR(255),

    amount NUMERIC(18,2) NOT NULL DEFAULT 0,

    years BIGINT,
    months BIGINT,

    priority TEXT,
    sub_title VARCHAR(255),
    title TEXT,
    type VARCHAR(100),

    summary_title VARCHAR(255),
    summary JSONB,
    recommendations JSONB,
    assumptions JSONB,
    feasibility JSONB,
    goal_table JSONB,

    timeline TEXT,
    target_amount VARCHAR(100),
    target_horizon VARCHAR(100),
    future_corpus_needed VARCHAR(100),
    lumpsum_needed_today VARCHAR(100),
    monthly_s_ip_required VARCHAR(100),
    years_months_left VARCHAR(100),
    selected_timeline VARCHAR(100),
    achievable_timeline VARCHAR(100),
    extra_time_required VARCHAR(100),
    current_monthly_savings VARCHAR(100),
    required_monthly_income VARCHAR(100),

    ai_advisory_note TEXT,
    expected_return VARCHAR(100),
    inflation_used VARCHAR(100),
    planning_style VARCHAR(100),

    goal_name VARCHAR(255),
    goal_type_display VARCHAR(100),
    target_amount_today VARCHAR(100),

    is_retirement BOOLEAN NOT NULL DEFAULT FALSE,
    is_annual_budget BOOLEAN NOT NULL DEFAULT FALSE,

    goal_sequence INTEGER NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_financial_planner_selected_goals_amount
        CHECK (amount > 0),

    CONSTRAINT chk_financial_planner_selected_goals_months
        CHECK (months >= 0),

    CONSTRAINT chk_financial_planner_selected_goals_sequence
        CHECK (goal_sequence > 0),

    CONSTRAINT chk_financial_planner_selected_goals_years
        CHECK (years >= 0),

    CONSTRAINT uq_financial_planner_goals_report_key
        UNIQUE (report_id, goal_key),

    CONSTRAINT uq_financial_planner_goals_report_sequence
        UNIQUE (report_id, goal_sequence),

    CONSTRAINT financial_planner_selected_goals_report_id_fkey
        FOREIGN KEY (report_id)
        REFERENCES public.financial_planner_reports(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX idx_financial_planner_selected_goals_report_id
ON public.financial_planner_selected_goals(report_id);

CREATE INDEX idx_financial_planner_selected_goals_goal_key
ON public.financial_planner_selected_goals(goal_key);

CREATE INDEX idx_financial_planner_selected_goals_goal_type
ON public.financial_planner_selected_goals(goal_type);

CREATE INDEX idx_financial_planner_selected_goals_created_at
ON public.financial_planner_selected_goals(created_at DESC);

CREATE OR REPLACE FUNCTION
    public.set_financial_planner_selected_goals_updated_at()
RETURNS TRIGGER AS
$$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$
LANGUAGE plpgsql;

CREATE TRIGGER trg_financial_planner_selected_goals_updated_at
BEFORE UPDATE
ON public.financial_planner_selected_goals
FOR EACH ROW
EXECUTE FUNCTION
    public.set_financial_planner_selected_goals_updated_at();